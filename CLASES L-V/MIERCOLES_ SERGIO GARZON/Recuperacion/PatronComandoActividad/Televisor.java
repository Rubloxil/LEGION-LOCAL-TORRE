public class Televisor {

    public void encender() {
        System.out.println("El televisor está encendido.");
    }

    public void apagar() {
        System.out.println("El televisor está apagado.");
    }

    public void subirVolumen() {
        System.out.println("El volumen ha aumentado.");
    }

    public void abrirApp() {
        System.out.println("Aplicación abierta.");
    }

    public void conectarWifi() {
        System.out.println("Televisor conectado al WiFi.");
    }

    public void actualizarFecha() {
        System.out.println("Fecha actualizada correctamente.");
    }
}